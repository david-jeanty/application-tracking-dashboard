/**
 * Generates the two committed files that come from the playbook sources:
 *
 * - `lib/agent/playbook/standards.generated.ts`: docs/STANDARDS.md split into
 *   its three parts, so the server can serve the matching parts without
 *   reading the docs folder at runtime (which a serverless deployment may not
 *   ship).
 * - `skill/interndex-pipeline/SKILL.md`: the Claude skill, rendered from the
 *   same phase steps `get_playbook` serves.
 *
 * Pure string functions with no runtime imports, so
 * `scripts/build-agent-playbook.mjs` can load this file directly with Node
 * and the unit test can call the same functions to prove the committed files
 * are current.
 */

import type {
  PhaseDefinition,
  PlaybookPhase,
  StandardsPart,
} from "./phases";

export type StandardsParts = Record<StandardsPart, string>;

const PART_HEADINGS: ReadonlyArray<[StandardsPart, string]> = [
  ["working", "## Part 1"],
  ["bullets", "## Part 2"],
  ["outreach", "## Part 3"],
];

/** Splits docs/STANDARDS.md at its three "## Part" headings. */
export function splitStandards(markdown: string): StandardsParts {
  const normalized = markdown.replace(/\r\n/g, "\n");
  const starts = PART_HEADINGS.map(([part, heading]) => {
    const index = normalized.indexOf(`\n${heading}`);
    if (index === -1) {
      throw new Error(`docs/STANDARDS.md has no "${heading}" heading.`);
    }
    return { part, index: index + 1 };
  });

  const parts = {} as StandardsParts;
  starts.forEach(({ part, index }, position) => {
    const end = starts[position + 1]?.index ?? normalized.length;
    parts[part] = normalized
      .slice(index, end)
      .replace(/\n-{3,}\s*$/, "")
      .trim();
  });
  return parts;
}

export function renderStandardsModule(parts: StandardsParts): string {
  return [
    "// Generated by scripts/build-agent-playbook.mjs from docs/STANDARDS.md.",
    "// Do not edit by hand: change docs/STANDARDS.md and run `npm run agent:playbook`.",
    "",
    `export const STANDARDS_PARTS = ${JSON.stringify(parts, null, 2)} as const;`,
    "",
  ].join("\n");
}

const SKILL_DESCRIPTION =
  "Runs David's Interndex recruiting pipeline through the Interndex connector. Use when David pastes a job description or asks to run on a posting (fit read, tailored resume, resume.lol build), and for story library sessions and the one-time library import.";

export function renderSkill(
  phases: readonly PlaybookPhase[],
  definitions: Readonly<Record<PlaybookPhase, PhaseDefinition>>,
): string {
  const lines = [
    "---",
    "name: interndex-pipeline",
    `description: ${SKILL_DESCRIPTION}`,
    "---",
    "",
    "# Interndex pipeline",
    "",
    "<!-- Generated by scripts/build-agent-playbook.mjs from lib/agent/playbook/phases.ts. Do not edit by hand. -->",
    "",
    "Interndex holds the playbook, David's standards, his saved rules and his story library. Always start by calling `get_playbook` with the phase below: its standards and saved rules override anything here.",
    "",
  ];

  for (const phase of phases) {
    const definition = definitions[phase];
    lines.push(`## ${definition.title}`, "", `Phase: \`${phase}\`. ${definition.when}`, "");
    definition.steps.forEach((step, index) => lines.push(`${index + 1}. ${step}`));
    lines.push("");
  }

  return lines.join("\n");
}
