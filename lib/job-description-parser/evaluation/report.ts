import {
  collectDefects,
  defectPriority,
} from "@/lib/job-description-parser/evaluation/evaluate";
import { summarizeCorpus } from "@/lib/job-description-parser/evaluation/metrics";
import {
  DEFECT_PRIORITY_LABELS,
  FIELD_LABELS,
  type FieldOutcome,
  type FixtureEvaluation,
} from "@/lib/job-description-parser/evaluation/types";

const OUTCOME_LABELS: Record<FieldOutcome["kind"], string> = {
  correct: "correct",
  incorrect: "incorrect",
  missing: "missing",
  "expected-absence": "expected absence",
  fabricated: "fabricated",
};

const GRADE_LABELS = {
  "fully-correct": "fully correct",
  usable: "usable with minor edits",
  unusable: "unusable result",
} as const;

function percent(value: number): string {
  return `${(value * 100).toFixed(1)}%`;
}

/** Keeps free text from breaking out of a markdown table cell. */
function cell(value: string | null): string {
  if (value === null || value.length === 0) return "—";
  const flattened = value.replace(/\s+/g, " ").replace(/\|/g, "\\|").trim();
  return flattened.length > 70 ? `${flattened.slice(0, 69)}…` : flattened;
}

function outcomeMarker(outcome: FieldOutcome): string {
  if (outcome.kind === "correct" || outcome.kind === "expected-absence") {
    return "ok";
  }
  return outcome.prefilled ? "**FAIL**" : "warn";
}

export function renderFixtureSection(evaluation: FixtureEvaluation): string {
  const lines: string[] = [
    `### ${evaluation.name}`,
    "",
    `Tags: ${evaluation.tags.join(", ")}`,
    "",
    `Verdict: **${GRADE_LABELS[evaluation.grade]}**`,
    "",
    "| Field | Expected | Extracted | Outcome | Confidence | Prefilled | Confidence OK | Evidence | Warnings |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
  ];

  for (const outcome of evaluation.outcomes) {
    lines.push(
      [
        "",
        FIELD_LABELS[outcome.field],
        cell(outcome.expected),
        cell(outcome.extracted),
        `${outcomeMarker(outcome)} ${OUTCOME_LABELS[outcome.kind]}`,
        outcome.confidence ?? "none",
        outcome.prefilled ? "yes" : "no",
        outcome.confidenceAppropriate ? "yes" : `no (${outcome.calibration})`,
        cell(outcome.evidence),
        cell(outcome.warnings.join(" ")),
        "",
      ].join(" | ").trim(),
    );
  }

  return lines.join("\n");
}

export function renderReport(
  evaluations: FixtureEvaluation[],
  options: { today: Date; parserVersion: string },
): string {
  const metrics = summarizeCorpus(evaluations);
  const defects = collectDefects(evaluations);

  const lines: string[] = [
    "# Job description parser evaluation",
    "",
    "Generated by `tests/unit/parser-evaluation.test.ts`. Do not edit by hand;",
    "regenerate with `WRITE_PARSER_REPORT=1 npm run test`.",
    "",
    `- Parser version: \`${options.parserVersion}\``,
    `- Date anchor: \`${options.today.toISOString().slice(0, 10)}\` (fixes year inference so runs are reproducible)`,
    `- Fixtures: ${metrics.fixtureCount}`,
    "",
    "## Outcome definitions",
    "",
    "| Outcome | Meaning |",
    "| --- | --- |",
    "| correct | The posting states the field and the parser extracted it correctly. |",
    "| incorrect | The posting states the field but the parser extracted a different value. |",
    "| missing | The posting states the field and the parser found nothing. |",
    "| expected absence | The posting does not state the field and the parser correctly stayed blank. |",
    "| fabricated | The posting does not state the field but the parser produced a value. |",
    "",
    "A field counts as blank when its confidence is `null`. The category and work",
    "arrangement fields fall back to `Other` and `Unknown` with null confidence, so",
    "those placeholders are scored as blanks rather than as extracted values.",
    "",
    "## Fixture verdicts",
    "",
    "| Verdict | Meaning | Count |",
    "| --- | --- | --- |",
    `| Fully correct | Every field is correct or a correct blank. | ${metrics.fullyCorrect} |`,
    `| Usable with minor edits | Some fields are blank or wrong, but every wrong value stayed below the prefill threshold, so the user only ever adds information. | ${metrics.usable} |`,
    `| Unusable result | At least one wrong or fabricated value was confident enough to populate the form. | ${metrics.unusable} |`,
    "",
    `Wrong or fabricated values that would reach the form: **${metrics.prefilledDefects}**`,
    "",
    "## Per-field metrics",
    "",
    "| Field | Precision | Recall | Exact match | Correct | Incorrect | Missing | Expected absence | Fabricated | High-conf wrong | Med-conf wrong |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
  ];

  for (const field of metrics.fields) {
    lines.push(
      [
        "",
        FIELD_LABELS[field.field],
        percent(field.precision),
        percent(field.recall),
        percent(field.exactMatchAccuracy),
        String(field.correct),
        String(field.incorrect),
        String(field.missingCount),
        String(field.expectedAbsence),
        String(field.falsePositiveCount),
        String(field.highConfidenceWrongCount),
        String(field.mediumConfidenceWrongCount),
        "",
      ].join(" | ").trim(),
    );
  }

  lines.push("", "## Outstanding defects, in fix order", "");

  if (!defects.length) {
    lines.push("None. Every field is correct, a correct blank, or a hedged miss.");
  } else {
    lines.push(
      "| Priority | Class | Fixture | Field | Expected | Extracted | Confidence |",
      "| --- | --- | --- | --- | --- | --- | --- |",
    );
    for (const defect of defects) {
      lines.push(
        [
          "",
          String(defect.priority),
          DEFECT_PRIORITY_LABELS[defect.priority],
          defect.fixture,
          FIELD_LABELS[defect.outcome.field],
          cell(defect.outcome.expected),
          cell(defect.outcome.extracted),
          defect.outcome.confidence ?? "none",
          "",
        ].join(" | ").trim(),
      );
    }
  }

  lines.push("", "## Per-fixture detail", "");
  for (const evaluation of evaluations) {
    lines.push(renderFixtureSection(evaluation), "");
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

export { collectDefects, defectPriority, summarizeCorpus };
